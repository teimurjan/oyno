const plurals = new Intl.PluralRules("ru");
const list = new Intl.ListFormat("ru");

/** Picks the form a count takes: one, few, many. */
const counted = (count: number, one: string, few: string, many: string) => {
  const form = plurals.select(count);
  return `${count} ${form === "one" ? one : form === "few" ? few : many}`;
};

const lowerFirst = (text: string) => text.charAt(0).toLowerCase() + text.slice(1);

// "Рабочая память" after a verb takes the accusative; the other skill labels do not change.
const accusative = (label: string) => lowerFirst(label).replace(/ая(?=\s|$)/g, "ую");

const minutesWord = (minutes: number) => counted(minutes, "минута", "минуты", "минут");

